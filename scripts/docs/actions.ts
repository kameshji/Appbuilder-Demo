/**
 * docs/reference/connector-actions.md: the built-in actions of the action connectors (HTTP, Email), generated from the
 * providers' definitions (server/core/actions). Pure: no server, no database.
 */
import type { ActionDef, JsonSchema } from '../../server/core/actions/contracts.ts'
import { BUILTIN_ACTIONS } from '../../server/core/actions/builtin-defs.ts'

const typeText = (s: JsonSchema): string => {
  if (s.anyOf) return s.anyOf.map(typeText).join(' or ')
  if (s.enum) return s.enum.map((e) => `\`${String(e)}\``).join(', ')
  const t = Array.isArray(s.type) ? s.type.join(' or ') : s.type ?? 'any'
  if (t === 'array' && s.items) return `list of ${typeText(s.items)}`
  if (t === 'object' && s.additionalProperties && typeof s.additionalProperties === 'object') return `object (names to ${typeText(s.additionalProperties)})`
  return s.format ? `${t} (${s.format})` : t
}
const cell = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ')

function table(schema: JsonSchema): string[] {
  const props = schema.properties ?? {}
  const order = [...(schema['x-order'] ?? []), ...Object.keys(props).filter((k) => !(schema['x-order'] ?? []).includes(k))]
  if (!order.length) return ['(none)', '']
  const lines = ['| Name | Type | Required | Description |', '| --- | --- | --- | --- |']
  for (const k of order) {
    const p = props[k]
    if (!p) continue
    const def = p.default !== undefined ? ` Default \`${JSON.stringify(p.default)}\`.` : ''
    lines.push(`| \`${k}\` | ${cell(typeText(p))} | ${schema.required?.includes(k) ? 'yes' : ''} | ${cell((p.description ?? p.title ?? '') + def)} |`)
  }
  return [...lines, '']
}

function action(kind: string, a: ActionDef): string[] {
  return [
    `### ${kind}: \`${a.id}\` (${a.title})`, '',
    a.description, '',
    `Idempotent: ${a.idempotent ? 'yes' : 'no'}. Side effect: ${a.sideEffect === 'external' ? 'external (a flow must pass an idempotency key; a repeated key returns the stored result for 24 hours)' : 'none'}. Time limit: ${a.timeoutMs / 1000} s.`, '',
    '**Inputs**', '', ...table(a.inputs),
    '**Outputs**', '', ...table(a.outputs),
  ]
}

export function buildActionsPage(): { text: string } {
  const providers = BUILTIN_ACTIONS.map((b) => ({ ...b, builtin: () => b.actions }))
  const lines = [
    '# Connector actions (reference)',
    '',
    '<!-- Generated by `npm run docs:gen` from server/core/actions (HTTP and Email providers). Do not edit by hand. -->',
    '',
    'Built-in actions of the action connectors. Custom actions of an HTTP connection (made with the form or imported from',
    'OpenAPI) are listed on the connection\'s Actions tab. How actions run, the limits and the error codes:',
    '[docs/dev/connectors.md](../dev/connectors.md#connector-actions); for makers:',
    '[connections and actions](../guide/maker/connections-and-actions.md).',
    '',
    '| Connector | Kind | Actions |',
    '| --- | --- | --- |',
    ...providers.map((p) => `| ${p.label} | \`${p.kind}\` | ${p.builtin().map((a) => `\`${a.id}\``).join(', ')} |`),
    '',
    '## Error codes',
    '',
    '| Code | Retryable | Meaning |',
    '| --- | --- | --- |',
    '| `invalid_input` | no | The inputs do not fit the action\'s schema (or a template value is missing). |',
    '| `not_found` | no | The connection or action does not exist. |',
    '| `denied` | no | Not allowed (attachment the identity cannot open, every recipient suppressed). |',
    '| `blocked` | no | Outbound policy: host not on the allow-list, a forbidden address, a refused redirect. |',
    '| `rate_limited` | yes | The connection\'s rate or concurrency limit, or the remote answered 429. |',
    '| `circuit_open` | yes | Calls are paused after 5 failures in a row (30 s, doubling to 5 minutes). |',
    '| `timeout` | yes | No answer within the time limit. |',
    '| `network` | yes (not for TLS) | Connect, reset or certificate problems. |',
    '| `upstream` | 5xx yes, 4xx no | The remote answered with an unexpected status. |',
    '| `too_large` | no | The response, the output or the inputs are above the caps. |',
    '| `limit` | yes | An email sending limit of the environment. |',
    '| `in_progress` | yes | The same idempotency key is running right now. |',
    '| `not_configured` | no | A secret or setting of the connection is missing (or OAuth refused the client). |',
    '| `unavailable` | yes | The server cannot do it now (email not set up). |',
    '',
    '## Actions',
    '',
  ]
  for (const p of providers) for (const a of p.builtin()) lines.push(...action(p.label, a))
  return { text: lines.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n' }
}
