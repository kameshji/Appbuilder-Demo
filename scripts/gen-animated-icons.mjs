// Regenerates src/fx/animatedIcons.ts from react-useanimations/catalog.json.
// Run: node scripts/gen-animated-icons.mjs   (a unit test fails if the file drifts from the catalog)
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const catalog = JSON.parse(readFileSync(new URL('../node_modules/react-useanimations/catalog.json', import.meta.url), 'utf8'))
const ids = catalog.map((c) => c.export).sort((a, b) => a.localeCompare(b))
const lines = []
for (let i = 0; i < ids.length; i += 8) lines.push('  ' + ids.slice(i, i + 8).map((x) => `'${x}'`).join(', ') + ',')
const out = `/**
 * GENERATED by scripts/gen-animated-icons.mjs from react-useanimations/catalog.json. Do not edit by hand.
 * One entry per animated icon: its export name (the lib/<id> module), which is the id used in "anim:<id>".
 */
export const ANIMATED_ICON_IDS: readonly string[] = [
${lines.join('\n')}
]
`
writeFileSync(fileURLToPath(new URL('../src/fx/animatedIcons.ts', import.meta.url)), out)
console.log(`wrote ${ids.length} ids`)
