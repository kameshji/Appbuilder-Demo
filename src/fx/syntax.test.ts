import { describe, expect, it } from 'vitest'
import { check } from './index.ts'
import { err, run, val } from './testutil.ts'

describe('literals and basics', () => {
  it('evaluates literals', () => {
    expect(val('=12')).toBe(12)
    expect(val('=3.5')).toBe(3.5)
    expect(val('=1e3')).toBe(1000)
    expect(val('="hi"')).toBe('hi')
    expect(val('="say ""hi"""')).toBe('say "hi"')
    expect(val('=true')).toBe(true)
    expect(val('=false')).toBe(false)
    expect(val('=  7  ')).toBe(7)
  })
  it('blank formula is null', () => {
    expect(val('=')).toBeNull()
    expect(val('=   ')).toBeNull()
    expect(val('= // just a comment')).toBeNull()
  })
  it('requires a leading =', () => {
    const e = err('1+2')
    expect(e.message).toMatch(/start with =/)
    expect(check('hello')).toHaveLength(1)
  })
  it('comments', () => {
    expect(val('=1 + /* two */ 2 // three')).toBe(3)
    expect(val('=1 + 1 // tail\n')).toBe(2)
    expect(err('=1 /* open').message).toMatch(/Comment/)
  })
  it('records and tables', () => {
    expect(val('={Name: "A", Age: 3}')).toEqual({ Name: 'A', Age: 3 })
    expect(val('={}')).toEqual({})
    expect(val('=[1, 2, 3]')).toEqual([{ Value: 1 }, { Value: 2 }, { Value: 3 }])
    expect(val('=[{a: 1}, {a: 2}]')).toEqual([{ a: 1 }, { a: 2 }])
    expect(val('=[]')).toEqual([])
    expect(val('=Table({a: 1}, {a: 2})')).toEqual([{ a: 1 }, { a: 2 }])
    expect(val('={a: {b: [1]}}.a.b')).toEqual([{ Value: 1 }])
  })
  it('quoted identifiers', () => {
    expect(val("='My Var' + 1", { 'My Var': 4 })).toBe(5)
    expect(val("='It''s' & \"\"", { "It's": 'ok' })).toBe('ok')
  })
})

describe('operators and precedence', () => {
  it('arithmetic', () => {
    expect(val('=1 + 2 * 3')).toBe(7)
    expect(val('=(1 + 2) * 3')).toBe(9)
    expect(val('=10 - 4 - 3')).toBe(3)
    expect(val('=20 / 4 / 5')).toBe(1)
    expect(val('=2 ^ 3')).toBe(8)
    expect(val('=2 * 3 ^ 2')).toBe(18)
    expect(val('=-5 + 2')).toBe(-3)
    expect(val('=-(2 + 3)')).toBe(-5)
    expect(val('=50%')).toBe(0.5)
    expect(val('=200 * 10%')).toBe(20)
    expect(val('=0.1 + 0.2')).toBeCloseTo(0.3)
  })
  it('unary minus binds tighter than ^ (spec order)', () => {
    expect(val('=-2 ^ 2')).toBe(4)
  })
  it('blank is zero in arithmetic and empty in concat', () => {
    expect(val('=Blank() + 1')).toBe(1)
    expect(val('=Blank() * 5')).toBe(0)
    expect(val('="a" & Blank() & "b"')).toBe('ab')
    expect(val('=x + 1', { x: null })).toBe(1)
  })
  it('text numbers convert', () => {
    expect(val('="3" + 4')).toBe(7)
    expect(val('="1,000" * 2')).toBe(2000)
  })
  it('concat and numbers in text', () => {
    expect(val('="n=" & 5')).toBe('n=5')
    expect(val('="n=" & 1.50')).toBe('n=1.5')
    expect(val('=true & "x"')).toBe('truex')
    expect(val('=1 + 2 & "x"')).toBe('3x')
  })
  it('comparison', () => {
    expect(val('=1 < 2')).toBe(true)
    expect(val('=2 <= 2')).toBe(true)
    expect(val('=3 > 4')).toBe(false)
    expect(val('=4 >= 5')).toBe(false)
    expect(val('=1 <> 2')).toBe(true)
    expect(val('=2 = 2')).toBe(true)
    expect(val('="b" > "a"')).toBe(true)
    expect(val('=1 + 1 = 2')).toBe(true)
    expect(val('="a" & "b" = "ab"')).toBe(true)
  })
  it('= is case-insensitive for text, blank equals blank', () => {
    expect(val('="ABC" = "abc"')).toBe(true)
    expect(val('="ABC" <> "abc"')).toBe(false)
    expect(val('=Blank() = Blank()')).toBe(true)
    expect(val('=Blank() = ""')).toBe(true)
    expect(val('=Blank() = 0')).toBe(true)
    expect(val('=Blank() = "x"')).toBe(false)
    expect(val('=x = 1', { x: null })).toBe(false)
  })
  it('in and exactin', () => {
    expect(val('="ell" in "Hello"')).toBe(true)
    expect(val('="ELL" in "Hello"')).toBe(true)
    expect(val('="ELL" exactin "Hello"')).toBe(false)
    expect(val('="ell" exactin "Hello"')).toBe(true)
    expect(val('="" in "Hello"')).toBe(true)
    expect(val('="x" in Blank()')).toBe(false)
    expect(val('=2 in [1, 2, 3]')).toBe(true)
    expect(val('=5 in [1, 2, 3]')).toBe(false)
    expect(val('="B" in ["a", "b"]')).toBe(true)
    expect(val('="B" exactin ["a", "b"]')).toBe(false)
  })
  it('logic operators and precedence', () => {
    expect(val('=true && false')).toBe(false)
    expect(val('=true || false')).toBe(true)
    expect(val('=true And false')).toBe(false)
    expect(val('=false Or true')).toBe(true)
    expect(val('=true || false && false')).toBe(true)
    expect(val('=1 < 2 && 2 < 3')).toBe(true)
    expect(val('=!true')).toBe(false)
    expect(val('=Not true')).toBe(false)
    expect(val('=Not(false)')).toBe(true)
    expect(val('=!(1 = 2)')).toBe(true)
  })
  it('&& and || short-circuit', () => {
    expect(val('=false && (1/0 = 1)')).toBe(false)
    expect(val('=true || (1/0 = 1)')).toBe(true)
  })
  it('& binds looser than + and tighter than =', () => {
    expect(val('="a" & 1 + 2 = "a3"')).toBe(true)
  })
  it('division by zero is an error', () => {
    const e = err('=1 / 0')
    expect(e.message).toBe("Can't divide by zero")
    expect(e.start).toBe(5)
    expect(e.end).toBe(6)
  })
  it('type errors with spans', () => {
    const e = err('=1 + "abc"')
    expect(e.message).toMatch(/Can't turn the text "abc" into a number/)
    expect(e.start).toBe(5)
    expect(e.end).toBe(10)
    expect(err('={a: 1} + 1').message).toMatch(/record/)
    expect(err('=[1] & "x"').message).toMatch(/table/)
  })
})

describe('string interpolation', () => {
  it('interpolates', () => {
    expect(val('=$"Hi {Name}!"', { Name: 'Asha' })).toBe('Hi Asha!')
    expect(val('=$"{1 + 2} and {"x"}"')).toBe('3 and x')
    expect(val('=$"plain"')).toBe('plain')
    expect(val('=$"{{braces}}"')).toBe('{braces}')
    expect(val('=$"a ""q"" {1}"')).toBe('a "q" 1')
    expect(val('=$"{$"in {1}"}!"')).toBe('in 1!')
    expect(val('=$"{{ {Upper("a")} }}"')).toBe('{ A }')
  })
  it('reports errors inside holes at the right offset', () => {
    const e = err('=$"Hi {Buton1}"')
    expect(e.message).toBe("Name isn't recognised: Buton1")
    expect(e.start).toBe(7)
    expect(e.end).toBe(13)
    expect(err('=$"x {}"').message).toMatch(/Empty/)
  })
})

describe('member access', () => {
  it('reads fields', () => {
    expect(val('=p.Name', { p: { Name: 'A' } })).toBe('A')
    expect(val('=p.Missing', { p: { Name: 'A' } })).toBeNull()
    expect(val('=p.Name', { p: null })).toBeNull()
    expect(val('=a.b.c', { a: { b: { c: 9 } } })).toBe(9)
    expect(val('=a.b.c', { a: { b: null } })).toBeNull()
  })
  it('errors on non-records', () => {
    const e = err('=n.Foo', { n: 5 })
    expect(e.message).toMatch(/Can't read \.Foo from a number/)
    expect(e.start).toBe(3)
    expect(err('=t.Foo', { t: [{ a: 1 }] }).message).toMatch(/table/)
  })
})

describe('syntax errors', () => {
  it('reports unclosed things', () => {
    expect(err('="abc').message).toMatch(/closing quote/)
    expect(err('=Len("a"').message).toMatch(/Missing \)/)
    expect(err('=(1 + 2').message).toMatch(/Missing \)/)
    expect(err('=[1, 2').message).toMatch(/Missing \]/)
    expect(err('={a: 1').message).toMatch(/Missing \}/)
  })
  it('reports unexpected tokens with spans', () => {
    const e = err('=1 + * 2')
    expect(e.message).toMatch(/Unexpected \*/)
    expect(e.start).toBe(5)
    expect(err('=1 2').message).toMatch(/Unexpected 2/)
    expect(err('=1 ~ 2').message).toMatch(/Unexpected character: ~/)
    expect(err('=1 +').message).toMatch(/ends too early/)
    expect(err('=1 == 1').message).toMatch(/single =/)
    expect(err('=)').message).toMatch(/Unexpected \)/)
  })
  it('check() returns diagnostics', () => {
    expect(check('=1 + 2')).toEqual([])
    expect(check('=')).toEqual([])
    expect(check('=1 +')).toHaveLength(1)
    expect(check('=Foo(1)')[0]!.message).toBe("Function isn't recognised: Foo")
    expect(check('=filter(a, b)')[0]!.message).toBe('Did you mean Filter?')
    expect(check('=Filter(a)')[0]!.message).toMatch(/at least 2/)
    expect(check('=Len()')[0]!.message).toMatch(/needs 1 argument/)
    expect(check('=Back(1)')[0]!.message).toMatch(/doesn't take any/)
  })
  it('run reports syntax errors without throwing', () => {
    const r = run('=(((')
    expect(r.ok).toBe(false)
  })
})
